-- PARTE II - RELACIONAMENTO ENTRE TABELAS
-- USO DE JOINS
-- INTER JOIN - INNER JOIN ENTRE TABELAS
-- EX 19: PEDIDOS COM NOME DO CLIENTE

SELECT P.id_pedido, p.data_pedido, c.nome as cliente, p.valor_total
from pedido as p 
inner join cliente as c 
on c.id_cliente = p.cliente_ID

-- OBS: RELACIONE O CLIENTE CUJO ID_CLIENTE É IGUAL ID_CLIENTE GRAVADO NO PEDIDO
-- ALIASES - SAO COMO ATRIBUICAO DE PEDIDO PARA CONSULTAR DE VARIAS TABELAS MAIS CUSTAS E LEGIVEIS

--LEFT JOIN - MANTEM TODOS OS REGISTROS DA TABELA DA ESQUERDA MESMO QUANDO NAO POSSUI CORRESPONDENCIA
-- EX 20: TODOS OS CLINTE INCLUSIVE QUEM NUNCA COMPROU

SELECT C.NOME_PRODUTO, P.ID_PEDIDO, P.DATA_PEDIDO
FROM CLIENTE AS C 
LEFT JOIN PEDIDO AS P 
ON P.CLIENTE_ID = C.CLIENTE_ID
ORDER BY C.NOME;

-- EX 21: CLIENTES SEM PEDIDOS
SELECT C.ID_CLIENTE, C.NOME 
FROM CLIENTE AS C 
LEFT JOIN PEDIDO AS P  
ON P.CLIENTE_ID = C.ID_CLIENTE
WHERE P.ID_PEDIDO IS NULL;

-- JOIN COM TRES TABELA
-- EX 22: ITENS DE PEDIDO COM NOME DO PRODUTO
SELECT P.ID_PEDIDO, PR.NOME_PRODUTO AS PRODUTO, IP.QUANTIDADE, IP.
PRECO_UNITARIO, IP.QUANTIDADE * IP.PRECO_UNITARIO AS
SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN ITEM_PEDIDO AS IP 
ON IP.ID_PEDIDO = P.ID_PEDIDO
INNER JOIN PRODUTO AS  PR 
ON PR.ID_PRODUTO = IP.ID_PRODUTO
ORDER BY P.ID_PEDIDO;

-- EX 23: JOIN COM CATEGORIA - PRODUTO E NOME DE SUA CATEGORIA

SELECT PR.NOME AS PRODUTO, CA.NOME AS CATEGORIA, PR.PRECO
FROM PRODUTO AS PR
INNER JOIN CATEGORIA AS CA
ON CA.ID_CATEGORIA = PR.ID_CATEGORIA
ORDER BY CA.NOME, PR.NOME;

-- AGREGANDO JOINS
-- EX 24 - QUANTIDADES DE PRODUTOS POR CATEGORIA

SELECT CA.NOME AS CATEGORIA, COUNT(PR.ID_PRODUTO) AS QTDE_PRODUTOS
FROM CATEGORIA AS CA
LEFT JOIN PRODUTO AS PR 
ON PR.ID_CATEGORIA - CA.ID_CATEGORIA
GROUP BY CA.ID_CATEGORIA, CA.NOME 
ORDER BY QTDE_PRODUTOS DESC;

-- EX 25: TOTAL COMPRADO POR CLIENTE
SELECT C.NOME AS CLIENTE, 
COUNT(P.ID_PEDIDO) AS QTDE_PEDIDOS, 
SUM(P.VALOR_TOTAL) AS TOTAL_COMPRADO
FROM CLIENTE AS C 
INNER JOIN PEDIDO AS P 
ON P.CLIENTE_ID = C.ID_CLIENTE
WHERE P.STATUS_PEDIDO = 'ABERTO'
GROUP BY C.ID_CLIENTE, C.NOME
ORDER BY TOTAL_COMPRADO DESC;

-- RELATORIO COMPLETO DO PEDIDO
-- EX 26: COMBINACAO DE VARIAS TABELAS PARA UMA CONSULTA COMPLETA
SELECT P.ID_PEDIDO, DATE_FORMAT(P.DATA_PEDIDO, '%d %m %Y %H %i' ) 
AS DATA, C.NOME AS CLIENTE, PR.NOME_PRODUTO AS PRODUTO, IP.QUANTIDADE, IP.PRECO_UNITARIO,
IP.QUANTIDADE * IP.PRECO_UNITARIO AS SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN CLIENTE AS C 
ON C.ID_CLIENTE = P.CLIENTE_ID
INNER JOIN ITEM_PEDIDO AS IP
ON IP.ID_PEDIDO = P.ID_PEDIDO
INNER JOIN PRODUTO AS PR 
ON PR.ID_PRODUTO = IP.ID_PRODUTO
ORDER BY P.ID_PEDIDO, PR.NOME_PRODUTO;

-- OBS: DATE_FORMAT(P.DATA_PEDIDO, '%d %m %Y %H %i) - FORMATACAO PADRAO BRASIL

